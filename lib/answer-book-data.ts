// 将160条答案均匀分布到640页
// 使用固定算法保证同一页码永远得到同一答案（像真书一样）
function buildPageMap(): string[] {
  const unique = UNIQUE_ANSWERS.length;
  const pages: string[] = new Array(641); // 1-indexed, index 0 unused
  for (let page = 1; page <= 640; page++) {
    // 跨步分布：相邻页码尽量不重复同一答案
    const idx = ((page - 1) * 3 + Math.floor((page - 1) / unique)) % unique;
    pages[page] = UNIQUE_ANSWERS[idx];
  }
  return pages;
}

const PAGE_ANSWERS = buildPageMap();

export function getAnswerByPage(page: number): string {
  return PAGE_ANSWERS[page] ?? UNIQUE_ANSWERS[0];
}

export function pickRandomPage(excludePage?: number): number {
  let page: number;
  do {
    page = Math.floor(Math.random() * 640) + 1;
  } while (page === excludePage);
  return page;
}

