function buildMinorArcana(): TarotCard[] {
  const cards: TarotCard[] = [];
  const enNames = ["Ace", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine", "Ten", "Page", "Knight", "Queen", "King"];

  for (const { suit, suitCN, element, domain } of suits) {
    const names = minorNames[suit];
    const meanings = minorMeanings[suit];
    for (let i = 1; i <= 14; i++) {
      const m = meanings[i];
      cards.push({
        id: 22 + suits.findIndex(s => s.suit === suit) * 14 + (i - 1),
        name: `${enNames[i - 1]} of ${suit.charAt(0).toUpperCase() + suit.slice(1)}`,
        nameCN: names[i],
        arcana: "minor",
        suit,
        number: i,
        keywords: m.kw,
        uprightMeaning: m.up,
        reversedMeaning: m.rev,
        interpretation: m.interp,
        imageUrl: `/cards/${suit}-${String(i).padStart(2, "0")}.webp`,
        element,
      });
    }
  }
  return cards;
}

export const tarotCards: TarotCard[] = [...majorArcana, ...buildMinorArcana()];

export function getCardById(id: number): TarotCard {
  return tarotCards[id] ?? tarotCards[0];
}

export function getMajorArcana(): TarotCard[] {
  return tarotCards.filter(c => c.arcana === "major");
}

export function getCardsBySuit(suit: string): TarotCard[] {
  return tarotCards.filter(c => c.suit === suit);
}
